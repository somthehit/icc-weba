// db/schema/accounting.ts
//
// The shop books: a double-entry core plus the practical records around it.
//
//   accounts / journal_entries / journal_lines   double-entry general ledger
//   cod_settlements                              driver cash banked, and the JE it posted
//   suppliers / expenses / purchase_bills        the day-to-day paperwork
//
// The plain-arithmetic views the reports use, which anyone in the shop can check
// by hand, still hold alongside the ledger:
//
//   revenue (orders) - COGS (order_items.unit_cost_snapshot) = gross profit
//   gross profit - expenses                                  = net profit
//   VAT collected (orders) - VAT paid (expenses + bills)      = VAT payable
//   purchase_bills.total_amount - amount_paid                = accounts payable
//
// DDL: drizzle/migrations/0006_shop_books.sql (suppliers/expenses/bills),
// 0015_double_entry_accounting.sql (ledger), 0021_cod_settlements.sql (COD).

